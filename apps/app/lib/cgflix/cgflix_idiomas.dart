/// Os idiomas que o CGFLIX mais usa vêm primeiro nas listas (o resto segue em ordem alfabética).
const cgflixCommonLanguages = ['pt', 'en', 'ja', 'es'];

/// [items] com os idiomas de [cgflixCommonLanguages] no topo, na ordem dela.
List<T> cgflixCommonLanguagesFirst<T>(List<T> items, String Function(T) code1) => [
  for (final c in cgflixCommonLanguages) ...items.where((i) => code1(i) == c),
  ...items.where((i) => !cgflixCommonLanguages.contains(code1(i))),
];

